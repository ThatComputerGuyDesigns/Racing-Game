// Converts real-circuit centerlines (bacinger/f1-circuits GeoJSON, MIT) into
// track control points: src/sim/realtracks.js.  Usage: node tools/import-circuits.mjs <file.geojson>
import fs from 'fs';

const PICK = {
  spa:         { id: 'be-1925', name: 'Spa-Francorchamps', width: 14, runoff: 12, dir: 'R',
    blurb: 'The Ardennes epic: Eau Rouge-Raidillon, the Kemmel straight and flat-out Blanchimont.',
    elevation: [[0, 30], [0.05, 36], [0.11, 2], [0.15, 34], [0.27, 58], [0.33, 44], [0.43, 22], [0.55, 4], [0.66, -38], [0.84, -6], [0.94, 24]] },
  silverstone: { id: 'gb-1948', name: 'Silverstone', width: 15, runoff: 12, dir: 'R',
    blurb: 'Airfield speed: Copse, the Maggotts-Becketts-Chapel sequence and Stowe.',
    elevation: [[0, 0], [0.3, 3], [0.6, 1], [0.8, 4]] },
  monza:       { id: 'it-1922', name: 'Monza', width: 15, runoff: 12, dir: 'R',
    blurb: 'Temple of speed: slipstream battles, chicane braking zones, Parabolica.',
    elevation: [[0, 0], [0.4, 4], [0.7, 2]] },
  imola:       { id: 'it-1953', name: 'Imola', width: 12, runoff: 9, dir: 'L',
    blurb: 'Old-school and narrow: Tamburello, Tosa, the Piratella drop and Acque Minerali.',
    elevation: [[0, 0], [0.22, 4], [0.38, 22], [0.48, 6], [0.58, -4], [0.7, 12], [0.85, 2]] },
  suzuka:      { id: 'jp-1962', name: 'Suzuka', width: 12, runoff: 10, dir: 'R',
    blurb: 'The figure-eight: the Esses, Degner, Spoon and the flat-out 130R.',
    // crossover: 39.8% passes under the bridge carrying 80.7%
    elevation: [[0, 0], [0.15, 12], [0.30, 18], [0.40, 16], [0.55, 14], [0.70, 20], [0.80, 27], [0.84, 26], [0.92, 6]],
    bridge: [0.398, 0.807] },
};

const src = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const out = {};
for (const [key, cfg] of Object.entries(PICK)) {
  const f = src.features.find(f => f.properties.id === cfg.id);
  let c = f.geometry.coordinates.map(p => [+p[0], +p[1]]);
  if (Math.hypot(c[0][0] - c.at(-1)[0], c[0][1] - c.at(-1)[1]) < 1e-6) c.pop();
  const lon0 = c.reduce((a, p) => a + p[0], 0) / c.length, lat0 = c.reduce((a, p) => a + p[1], 0) / c.length;
  const kx = 111320 * Math.cos(lat0 * Math.PI / 180), kz = 110540;
  // x = east, z = south keeps the map un-mirrored in a right-handed y-up world
  let pts = c.map(p => [(p[0] - lon0) * kx, -(p[1] - lat0) * kz]);
  pts = pts.filter((p, i) => i === 0 || Math.hypot(p[0] - pts[i - 1][0], p[1] - pts[i - 1][1]) > 3);
  // resample the closed polyline evenly (10 m) then gaussian-ish smooth (3 passes, +-1)
  // so the Catmull-Rom spline can't overshoot into loops at unevenly-spaced corners
  {
    const SP = 10, res = [];
    const n = pts.length;
    let carry = 0;
    for (let i = 0; i < n; i++) {
      const a = pts[i], b = pts[(i + 1) % n];
      const L = Math.hypot(b[0] - a[0], b[1] - a[1]);
      let d = carry;
      while (d < L) { const t = d / L; res.push([a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t]); d += SP; }
      carry = d - L;
    }
    pts = res;
    for (let pass = 0; pass < 3; pass++) {
      const m = pts.length;
      pts = pts.map((p, i) => { const a = pts[(i - 1 + m) % m], c = pts[(i + 1) % m]; return [(a[0] + 2 * p[0] + c[0]) / 4, (a[1] + 2 * p[1] + c[1]) / 4]; });
    }
  }
  // decide direction from the first real corner after the start line (left turn = +curvature)
  const firstTurn = (P) => {
    let d = 0;
    for (let i = 1; i < P.length - 1 && d < 1500; i++) {
      const a = P[i - 1], b = P[i], e = P[Math.min(P.length - 1, i + 6)];
      d += Math.hypot(b[0] - a[0], b[1] - a[1]);
      const h1 = Math.atan2(b[0] - a[0], b[1] - a[1]), h2 = Math.atan2(e[0] - b[0], e[1] - b[1]);
      const t = Math.atan2(Math.sin(h2 - h1), Math.cos(h2 - h1));
      if (Math.abs(t) > 0.35) return t > 0 ? 'L' : 'R';
    }
    return '?';
  };
  let ft = firstTurn(pts);
  if (ft !== cfg.dir) { pts = [pts[0], ...pts.slice(1).reverse()]; ft = firstTurn(pts) + ' (reversed)'; }
  let len = 0; for (let i = 0; i < pts.length; i++) { const a = pts[i], b = pts[(i + 1) % pts.length]; len += Math.hypot(b[0] - a[0], b[1] - a[1]); }
  console.log(key, 'pts', pts.length, 'len', len.toFixed(0), 'official', f.properties.length, 'first turn', ft);
  out[key] = { id: key, name: cfg.name, real: true, blurb: cfg.blurb, width: cfg.width, runoff: cfg.runoff,
    elevation: cfg.elevation, bridge: cfg.bridge, start: 0.004, points: pts.map(p => [+p[0].toFixed(1), +p[1].toFixed(1)]) };
}
const js = `// GENERATED by tools/import-circuits.mjs from bacinger/f1-circuits (MIT, see CREDITS.md).\n// Real-world circuit centerlines in metres (x = east, z = south).\nexport const REAL_TRACKS = ${JSON.stringify(out)};\n`;
fs.writeFileSync(new URL('../src/sim/realtracks.js', import.meta.url), js);
